#!/usr/bin/env bash
#
# Blink — automated installer
#
# Installs dependencies, builds the panel frontend, generates production
# secrets, builds the blinkd daemon and (optionally) the docs site.
#
# Usage:
#   ./install.sh [options]
#
# Options:
#   --skip-daemon           Do not build blinkd (skips the Rust toolchain)
#   --skip-docs             Do not build the documentation site
#   --systemd               Install systemd unit files (blink-panel, blinkd)
#   --no-frontend-build     Reuse an existing apps/panel/frontend/dist
#   -h, --help              Show this help
#
# The installer is idempotent: existing .env / blinkd.yml files are kept.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

# ---------------------------------------------------------------- appearance
if [[ -t 1 ]]; then
  BOLD=$'\033[1m'; DIM=$'\033[2m'; RED=$'\033[31m'; GREEN=$'\033[32m'
  YELLOW=$'\033[33m'; MAGENTA=$'\033[35m'; RESET=$'\033[0m'
else
  BOLD=""; DIM=""; RED=""; GREEN=""; YELLOW=""; MAGENTA=""; RESET=""
fi

step()  { printf "\n%s▸ %s%s\n" "${BOLD}${MAGENTA}" "$1" "${RESET}"; }
info()  { printf "  %s\n" "$1"; }
ok()    { printf "  %s✔ %s%s\n" "${GREEN}" "$1" "${RESET}"; }
warn()  { printf "  %s! %s%s\n" "${YELLOW}" "$1" "${RESET}"; }
fail()  { printf "  %s✖ %s%s\n" "${RED}" "$1" "${RESET}" >&2; exit 1; }

print_help() {
  sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//'
}

# ------------------------------------------------------------------- options
BUILD_DAEMON=1
BUILD_DOCS=1
INSTALL_SYSTEMD=0
BUILD_FRONTEND=1

for arg in "$@"; do
  case "$arg" in
    --skip-daemon)       BUILD_DAEMON=0 ;;
    --skip-docs)         BUILD_DOCS=0 ;;
    --systemd)           INSTALL_SYSTEMD=1 ;;
    --no-frontend-build) BUILD_FRONTEND=0 ;;
    -h|--help)           print_help; exit 0 ;;
    *)                   fail "unknown option: $arg (see --help)" ;;
  esac
done

cat <<'BANNER'

 ____  _      ___  _   _  _  __
| __ )| |    |_ _| \ | | | |/ /
|  _ \| |     | ||  \| | | ' /
| |_) | |___  | || |\  | | . \
|____/|_____| |___|_| \_| |_|\_\

Blink installer — panel, blinkd daemon and docs
BANNER

# ------------------------------------------------------------- prerequisites
step "Checking prerequisites"

if ! command -v bun >/dev/null 2>&1; then
  warn "bun is not installed."
  if command -v npm >/dev/null 2>&1; then
    info "attempting: npm install -g bun"
    npm install -g bun || fail "could not install bun automatically. Install it from https://bun.sh"
  else
    fail "Install bun from https://bun.sh and re-run this installer."
  fi
fi
ok "bun $(bun --version)"

if [[ "$BUILD_DAEMON" -eq 1 ]]; then
  if ! command -v cargo >/dev/null 2>&1; then
    if [[ -x "$HOME/.cargo/bin/cargo" ]]; then
      export PATH="$HOME/.cargo/bin:$PATH"
    else
      warn "cargo is not installed (needed to build blinkd)."
      info "install it with: curl https://sh.rustup.rs -sSf | sh -s -- -y --profile minimal"
      info "or re-run with --skip-daemon to build only the panel."
      fail "rust toolchain required for blinkd"
    fi
  fi
  ok "cargo $(cargo --version | awk '{print $2}')"
fi

if ! command -v openssl >/dev/null 2>&1; then
  fail "openssl is required to generate secrets"
fi
ok "openssl found"

if command -v docker >/dev/null 2>&1; then
  ok "docker found"
else
  warn "docker not found — nodes need it to run game servers (the panel does not)."
fi

# ------------------------------------------------------------------ bun deps
step "Installing workspace dependencies"
bun install
ok "workspaces installed"

# ------------------------------------------------------------ panel frontend
if [[ "$BUILD_FRONTEND" -eq 1 ]]; then
  step "Building panel frontend"
  bun --cwd apps/panel/frontend build
  ok "panel built -> apps/panel/frontend/dist"
else
  if [[ -f apps/panel/frontend/dist/index.html ]]; then
    warn "skipping frontend build (existing dist reused)"
  else
    fail "--no-frontend-build given but apps/panel/frontend/dist is missing"
  fi
fi

# ------------------------------------------------------------- panel secrets
step "Configuring panel environment"
ENV_FILE="apps/panel/server/.env"
if [[ -f "$ENV_FILE" ]]; then
  ok "keeping existing $ENV_FILE"
else
  JWT_SECRET="$(openssl rand -hex 32)"
  APP_KEY="$(openssl rand -hex 32)"
  cat > "$ENV_FILE" <<ENV
# Generated by install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
PORT=3000
APP_URL=http://localhost:3000
JWT_SECRET=$JWT_SECRET
APP_KEY=$APP_KEY
FIRST_USER_HAS_ADMIN=true
NODE_ENV=production
ENV
  chmod 600 "$ENV_FILE"
  ok "wrote $ENV_FILE with fresh secrets (set APP_URL to the public panel URL)"
fi

# ------------------------------------------------------------------- blinkd
BLINKD_BIN=""
if [[ "$BUILD_DAEMON" -eq 1 ]]; then
  step "Building blinkd (Rust, release mode — this takes a few minutes)"
  cargo build --release --manifest-path apps/blinkd/Cargo.toml
  mkdir -p bin
  cp apps/blinkd/target/release/blinkd bin/blinkd
  BLINKD_BIN="bin/blinkd"
  ok "daemon built -> bin/blinkd"

  step "Configuring blinkd"
  if [[ -f apps/blinkd/blinkd.yml ]]; then
    ok "keeping existing apps/blinkd/blinkd.yml"
  else
    cat > apps/blinkd/blinkd.yml <<YML
# blinkd configuration — see docs/blinkd-configuration
apiKey: $(openssl rand -hex 32)
bindAddress: 0.0.0.0
bindPort: 8080
volumesDirectory: ./volumes
appUrl: http://localhost:3000
corsOrigin: http://localhost:3000
validationCacheTtlSecs: 60
maxConnectionsPerIp: 10
maxUploadSizeMb: 100
YML
    chmod 600 apps/blinkd/blinkd.yml
    ok "wrote apps/blinkd/blinkd.yml (copy its apiKey into the panel's node form)"
  fi
else
  warn "skipping blinkd build (--skip-daemon)"
fi

# --------------------------------------------------------------------- docs
if [[ "$BUILD_DOCS" -eq 1 ]]; then
  step "Building documentation site"
  bun --cwd apps/docs build
  ok "docs built -> apps/docs/.next"
else
  warn "skipping docs build (--skip-docs)"
fi

# ------------------------------------------------------------------ systemd
if [[ "$INSTALL_SYSTEMD" -eq 1 ]]; then
  step "Installing systemd units"
  SVC_DIR="/etc/systemd/system"
  if [[ "$(id -u)" -ne 0 ]]; then
    fail "--systemd requires root (re-run with sudo)"
  fi

  PANEL_DIR="$SCRIPT_DIR/apps/panel/server"
  cat > "$SVC_DIR/blink-panel.service" <<UNIT
[Unit]
Description=Blink panel API
After=network.target

[Service]
Type=simple
WorkingDirectory=$PANEL_DIR
ExecStart=$(command -v bun) src/index.ts
Restart=on-failure
RestartSec=5
Environment=NODE_ENV=production

[Install]
WantedBy=multi-user.target
UNIT

  if [[ -n "$BLINKD_BIN" ]]; then
    DAEMON_DIR="$SCRIPT_DIR/apps/blinkd"
    cat > "$SVC_DIR/blinkd.service" <<UNIT
[Unit]
Description=Blink node daemon (blinkd)
After=network.target docker.service
Requires=docker.service

[Service]
Type=simple
WorkingDirectory=$DAEMON_DIR
ExecStart=$SCRIPT_DIR/bin/blinkd
Restart=on-failure
RestartSec=5

[Install]
WantedBy=multi-user.target
UNIT
  fi

  systemctl daemon-reload
  ok "installed blink-panel$( [[ -n "$BLINKD_BIN" ]] && echo ' and blinkd' ) services"
  info "start them with: sudo systemctl enable --now blink-panel blinkd"
fi

# ------------------------------------------------------------------ summary
step "Done"
info "Panel      : cd apps/panel/server && bun src/index.ts   (http://localhost:3000)"
if [[ -n "$BLINKD_BIN" ]]; then
  info "Daemon     : cd apps/blinkd && $SCRIPT_DIR/bin/blinkd   (port from blinkd.yml)"
fi
if [[ "$BUILD_DOCS" -eq 1 ]]; then
  info "Docs       : cd apps/docs && bun run start              (http://localhost:3001)"
fi
info ""
info "Next steps:"
info "  1. Open the panel and register, the first account becomes admin."
info "  2. Set APP_URL in apps/panel/server/.env to the public panel URL."
info "  3. Run blinkd on your nodes and add them under Admin → Nodes."
printf "\n"
